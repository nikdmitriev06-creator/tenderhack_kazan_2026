_LOOKUP = {alias.casefold(): canon for canon, aliases in _UNITS.items() for alias in aliases}
_LOOKUP.update({canon.casefold(): canon for canon in _UNITS})


def normalize_unit(text: str | None) -> str | None:
    """Каноническая единица или None, если это не похоже на единицу измерения."""
    if not text:
        return None
    key = re.sub(r"\s+", " ", text.strip()).casefold()
    return _LOOKUP.get(key) or _LOOKUP.get(key.rstrip("."))


def known_units() -> list[str]:
    return list(_UNITS)
